"""Stable paper tables and machine-readable metric definitions."""
from pathlib import Path
import csv,json
from common import read,jsonl,save
from protocol import VERSION,average,query_macro,paired_delta

TABLES=[
 ('A1. Labour retrieval — chất lượng', '1 Labour retrieval', ['unique_queries','group_recall_at_k','novel_group_precision_at_k','group_ndcg_at_k','mrr_at_k','all_groups_found']),
 ('A2. Labour retrieval — context và chi phí', '1 Labour retrieval', ['context_annotation_queries','estimated_context_tokens','fact_coverage','evidence_precision','mean_ms','p95_ms','successful_attempts','errors']),
 ('B. Labour QA — chất lượng', '2 Ablation', ['ai_correctness','ai_completeness','ai_evidence_support','ai_judged','expected_attempts','gold_citation_group_recall','task_answered_rate']),
 ('C. Labour QA — độ ổn định và chi phí', '2 Ablation', ['unique_queries','content_answers','technical_success_rate','mean_ms','p95_ms','content_mean_ms','errors','not_run','ai_judge_errors']),
 ('D. Zalo retrieval độc lập','3 Zalo retrieval',['unique_queries','recall_at_k','precision_at_k','mrr_at_k','ndcg_at_k','elapsed_ms','p95_ms','attempts']),
 ('E. VLSP QA thích nghi','4 VLSP adapted QA',['unique_queries','ai_correctness','ai_completeness','ai_evidence_support','ai_judged','expected_attempts','content_answers','mean_ms','p95_ms','errors','not_run'])]

def publish(output,status,rows):
    output=Path(output)
    for row in rows:
        stage={'1 Labour retrieval':'retrieval','2 Ablation':'ablation','3 Zalo retrieval':'zalo','4 VLSP adapted QA':'vlsp'}[row['section']]
        row['execution_status']=status['stages'].get(stage,{}).get('status','NOT_RUN')
        row['protocol_version']=VERSION
        row['fit_for_final_legal_claims']=False
        # These criteria gate an experimental comparison, not legal approval.
        row['execution_comparable']=row['execution_status']=='COMPLETE' and row.get('errors',0)==0 and row.get('not_run',0)==0
        if 'ai_judged' in row:
            row['judge_coverage_note']='READ_DENOMINATORS; compare paired/common judged queries, never unequal subset means'
    schema={'protocol_version':VERSION,'primary_k':read(output/'settings_resolved.json').get('k',10) if (output/'settings_resolved.json').exists() else None,
      'metrics':{
       'group_recall_at_k':'fraction of required evidence groups hit; alternatives within one group count once',
       'novel_group_precision_at_k':'distinct required groups hit / fixed k; NOT semantic Evidence Precision',
       'group_ndcg_at_k':'binary novelty gains for first hit per required group, log2 discount; macro average by query',
       'mrr_at_k':'reciprocal first required-group hit',
       'all_groups_found':'all annotated groups hit (qrels may be incomplete)',
       'fact_coverage':'facts with an annotated matching unit AND source quote in returned context / annotated facts; N/A without fact labels',
       'evidence_precision':'context units containing at least one annotated fact support quote / returned context units; N/A without fact labels',
       'estimated_context_tokens':'ceil(sum returned source characters / 4); estimator, NOT model tokenizer/billing',
       'ai_correctness':'mean separate AI judge score 0..1, NOT legal accuracy',
       'ai_completeness':'mean separate AI judge score 0..1',
       'ai_evidence_support':'mean separate AI judge support score 0..1, NOT human-groundedness',
       'task_answered_rate':'pipeline AnswerParts marked ANSWERED / emitted parts; machine completeness proxy',
       'draft_disposition_match_rate':'actual disposition matches draft expected action; technical errors remain failures in denominator',
       'mean_ms':'warm retrieval / QA worker wall time excluding model warmup and external AI judge; NOT frontend latency',
       'p95_ms':'nearest-rank 95th percentile on successful attempts; errors/not_run shown separately'},
      'statistics':'Queries are bootstrap units after averaging repetitions. Paired deltas are full-minus-ablation on common successfully judged queries only; report n and excluded IDs.',
      'gold_policy':'DRAFT remains DRAFT; no human/legal approval is generated by measurement.'}
    save(output/'metric_definitions.json',schema)
    lines=['# Bảng đo Pháp Điển AI — '+VERSION,'',
       '> Điểm chất lượng trong [0,1]; nhân 100 khi trình bày %. Cùng dataset/build/Gold/model/settings mới được đối chiếu.',
       '> DRAFT không phải Gold đã duyệt. N/A không phải 0. AI-judge không phải chứng nhận pháp lý.',
       '> Không dùng điểm của một cấu hình chấm 1 câu để so với cấu hình chấm 98 câu.',
       '', '| Nhóm | Trạng thái |','|---|---|']
    for stage in ('retrieval','ablation','zalo','vlsp'):lines.append(f"| {stage} | {status['stages'].get(stage,{}).get('status','NOT_RUN')} |")
    if schema['primary_k'] is not None:lines+=['',f"K chính: **{schema['primary_k']}**. Bảng phụ theo K nằm trong `retrieval/summary.json` và `retrieval_by_k.csv`."]
    for title,section,keys in TABLES:
        selected=[r for r in rows if r['section']==section]
        labels=', '.join(sorted({r['labels'] for r in selected})) or 'NOT_EVALUATED'
        lines+=['','## '+title,'',f'Nhãn: **{labels}**.','',
            '| Cấu hình | Trạng thái | '+' | '.join(keys)+' |','|---|---|'+'---:|'*len(keys)]
        percent={'group_recall_at_k','novel_group_precision_at_k','group_ndcg_at_k','mrr_at_k','all_groups_found',
            'recall_at_k','precision_at_k','ndcg_at_k','fact_coverage','evidence_precision','gold_citation_group_recall','task_answered_rate','technical_success_rate'}
        def fmt(k,v):
            if v is None:return 'N/A'
            if k in percent:return f'{100*v:.2f}%'
            if k=='estimated_context_tokens':return str(round(v))
            return f'{v:.4f}' if isinstance(v,float) else str(v)
        for r in selected:lines.append('| '+r['variant']+' | '+r['execution_status']+' | '+' | '.join(fmt(k,r.get(k)) for k in keys)+' |')
        if not selected:lines.append('| Chưa có kết quả | NOT_EVALUATED | '+' | '.join('N/A' for _ in keys)+' |')
    paired=[];retrieval=output/'retrieval/summary.json'
    if retrieval.exists():
        data=read(retrieval);by_k=[]
        for method,ks in data.get('metrics_by_k',{}).items():
            for k,metrics in ks.items():
                for metric,ci in metrics.items():by_k.append({'variant':method,'k':k,'metric':metric,**ci})
        write_csv(output/'retrieval_by_k.csv',by_k)
        for method,delta in data.get('paired_deltas_vs_hybrid',{}).items():paired.append({'track':'retrieval','metric':'group_recall_at_primary_k',**delta})
    for folder in ('ablation','vlsp_qa'):
        path=output/folder/'responses.jsonl'
        if not path.exists():continue
        records=jsonl(path)
        if folder=='ablation':
            from human_review import export_template
            export_template(output,records)
        names=sorted({r['variant'] for r in records})
        # Common intersection is computed on (query,repeat), not arbitrary per-method denominators.
        eligible={name:{(r['id'],r['repeat']) for r in records if r['variant']==name and r.get('status')=='OK' and r.get('judge',{}).get('status')=='AI_JUDGED'} for name in names}
        common=set.intersection(*eligible.values()) if len(names)>1 else next(iter(eligible.values()),set())
        common_report={'paired_keys':[list(k) for k in sorted(common)],'n_common_queries':len({k[0] for k in common}),'variants':{},
           'warning':'No quality ranking is justified with tiny or incomplete paired samples. Exact/profile shortcuts disabled only in ablation.'}
        for name in names:
            group=[r for r in records if r['variant']==name and (r['id'],r['repeat']) in common]
            common_report['variants'][name]={'n':len(group),**{'ai_'+key:average(query_macro(group,lambda r:r['judge'][key]).values()) for key in ('correctness','completeness','evidence_support')}}
        save(output/folder/'common_judged_comparison.json',common_report)
        summary_path=output/folder/'summary.json'
        if summary_path.exists():
            for name,metrics in read(summary_path).get('paired_deltas',{}).items():
                for metric,delta in metrics.items():paired.append({'track':folder,'metric':metric,**delta})
    write_csv(output/'paired_comparisons.csv',[{k:v for k,v in r.items() if not isinstance(v,list)} for r in paired])
    save(output/'paired_comparisons.json',paired)
    lines+=['','## Phạm vi và cách diễn giải',
       '- Bảng A: retrieval thuần; Graph là hybrid + mở rộng cấu trúc cố định có giới hạn. Các bản +rerank dùng cross-encoder trên cùng pool.',
       '- Bảng B/C: toàn pipeline có tắt từng thành phần trong benchmark worker; không phục vụ kết quả ablation cho người dùng.',
       '- Xem `component_exposure`: nếu graph/reviewer không thực sự chạy, không được gán cải thiện cho thành phần đó.',
       '- Fact Coverage/Evidence Precision cần nhãn fact→unit→quote riêng; thiếu thì N/A, không suy ra từ qrels/citations.',
       '- Chỉ có group precision không đủ kết luận precision ngữ nghĩa vì qrels hiện chưa đầy đủ.',
       '- Xem `common_judged_comparison.json`, CI và cỡ mẫu chung trước khi xếp hạng ablation. Không biến lỗi quota thành câu trả lời sai luật.',
       '- Zalo dùng toàn corpus riêng; VLSP là QA thích nghi theo phạm vi/ngày được công bố, không phải bảng xếp hạng chính thức.',
       '- Không đưa đáp án, qrels, nhãn fact/support hoặc reviewer verdict vào inference.',
       '- Gold đổi build phải ánh xạ và duyệt lại. Điểm cũ không được gán cho output OFFLINE mới.']
    (output/'comparison_tables.md').write_text('\n'.join(lines),encoding='utf-8')
    write_csv(output/'comparison_tables.csv',rows)
    save(output/'comparison_tables.json',{'protocol_version':VERSION,'stages':status['stages'],'rows':rows})

def write_csv(path,rows):
    fields=sorted({k for r in rows for k in r}) or ['status']
    with Path(path).open('w',encoding='utf-8-sig',newline='') as f:
        w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(rows)
